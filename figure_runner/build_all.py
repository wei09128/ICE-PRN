#!/usr/bin/env python3
"""Rebuild exactly Figures 1–4 and S1–S3 (layout v5.12) from bundled results; no refitting."""
from pathlib import Path
import argparse, hashlib, json, os, shutil, subprocess, sys, tempfile

P=Path(__file__).resolve().parent
STEMS=['Figure_1_two_system_transfer','Figure_2_scoring','Figure_3_biological_associations','Figure_4_capacity_and_p53_readouts',
       'Figure_S1_p53_direction_details','Figure_S2_identity_programs','Figure_S3_capacity_details']
SCRIPTS=['build_figure1.py','build_figure2.py','build_figure3.py','build_figure4.py','build_s1.py','build_s2.py','build_s3.py']


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out',type=Path,default=P/'figures')
    args=ap.parse_args();out=args.out.resolve();out.mkdir(parents=True,exist_ok=True)
    for name,digest in json.loads((P/'INPUT_HASHES.json').read_text()).items():
        if hashlib.sha256((P/name).read_bytes()).hexdigest()!=digest:
            raise RuntimeError('Saved input differs: '+name)
    logs=P/'logs';logs.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='ice_prn_figures_') as temp:
        stage=Path(temp);shutil.copytree(P/'inputs',stage/'inputs')
        for n in SCRIPTS+['_style.py','benchmark_CI.tsv','risk_CI.tsv','uncertainty_summary.json','coverage_intervals.tsv']:
            shutil.copy2(P/n,stage/n)
        env=os.environ.copy();env.update(MPLBACKEND='Agg',OPENBLAS_NUM_THREADS='1',OMP_NUM_THREADS='1')
        records=[]
        for script,stem in zip(SCRIPTS,STEMS):
            print('Building '+stem,flush=True)
            with (logs/(script+'.log')).open('w') as log:
                run=subprocess.run([sys.executable,str(stage/script)],cwd=stage,env=env,stdout=log,stderr=subprocess.STDOUT)
            if run.returncode:
                raise RuntimeError((logs/(script+'.log')).read_text())
            for ext in ['png','pdf','svg']:
                found=list((stage/'figures').rglob(stem+'.'+ext))
                if len(found)!=1:raise RuntimeError('Missing/duplicate rendered graphic: '+stem+'.'+ext)
                shutil.copy2(found[0],out/(stem+'.'+ext))
            records.append({'figure':stem,'status':'COMPLETE'})
        if (stage/'source_data').exists():
            shutil.copytree(stage/'source_data',P/'source_data',dirs_exist_ok=True)
        # Auxiliary numeric/provenance files generated by the existing builders.
        aux=P/'source_data/figure_build_records';aux.mkdir(exist_ok=True)
        for f in (stage/'figures').rglob('*'):
            if f.is_file() and f.suffix in ['.tsv','.json']:
                shutil.copy2(f,aux/f.name)
    expected=[s+'.'+e for s in STEMS for e in ['png','pdf','svg']]
    assert all((out/n).is_file() for n in expected)
    record={'status':'COMPLETE','version':'5.12','figures':len(STEMS),'graphic_files':len(expected),'models_refitted':False,
            'new_statistical_tests':False,'results':records,
            'sha256':{n:hashlib.sha256((out/n).read_bytes()).hexdigest() for n in expected}}
    (P/'BUILD_STATUS.json').write_text(json.dumps(record,indent=2)+'\n')
    print('COMPLETE: '+str(out),flush=True)


if __name__=='__main__':main()
